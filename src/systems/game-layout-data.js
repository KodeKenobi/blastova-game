function smoothPolylinePoints(points, samplesPerSegment = 5) {
  if (!Array.isArray(points) || points.length < 4) {
    return Array.isArray(points) ? points.map((point) => ({ x: point.x, y: point.y })) : [];
  }

  const result = [{ x: points[0].x, y: points[0].y }];

  const catmullRom = (p0, p1, p2, p3, t) => {
    const t2 = t * t;
    const t3 = t2 * t;
    return {
      x: 0.5 * ((2 * p1.x) + (-p0.x + p2.x) * t + (2 * p0.x - 5 * p1.x + 4 * p2.x - p3.x) * t2 + (-p0.x + 3 * p1.x - 3 * p2.x + p3.x) * t3),
      y: 0.5 * ((2 * p1.y) + (-p0.y + p2.y) * t + (2 * p0.y - 5 * p1.y + 4 * p2.y - p3.y) * t2 + (-p0.y + 3 * p1.y - 3 * p2.y + p3.y) * t3),
    };
  };

  for (let index = 0; index < points.length - 1; index += 1) {
    const p0 = points[Math.max(0, index - 1)];
    const p1 = points[index];
    const p2 = points[index + 1];
    const p3 = points[Math.min(points.length - 1, index + 2)];
    const startStep = index === 0 ? 0 : 1;

    for (let step = startStep; step <= samplesPerSegment; step += 1) {
      const t = step / samplesPerSegment;
      const point = catmullRom(p0, p1, p2, p3, t);
      const last = result[result.length - 1];
      if (!last || last.x !== point.x || last.y !== point.y) {
        result.push(point);
      }
    }
  }

  return result;
}

